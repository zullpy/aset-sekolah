    jenis VARCHAR(100) DEFAULT '',
    nama VARCHAR(255) NOT NULL,
    tingkat VARCHAR(50) DEFAULT '',
    beton VARCHAR(50) DEFAULT '',
    luas VARCHAR(50) DEFAULT '',
    letak_bangunan TEXT,
    dokumen VARCHAR(255) DEFAULT '',
    tgl_mulai VARCHAR(100) DEFAULT '',
    status_tanah VARCHAR(100) DEFAULT '',
    biaya VARCHAR(100) DEFAULT '',
