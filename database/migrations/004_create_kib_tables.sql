-- Migrasi 004: Membuat tabel KIB A sampai KIB F dan tabel riwayat aktivitas
CREATE TABLE IF NOT EXISTS kib_a (
    id INT AUTO_INCREMENT PRIMARY KEY,
    kode VARCHAR(100) NOT NULL UNIQUE,
    nama VARCHAR(255) NOT NULL,
    no_reg VARCHAR(50) DEFAULT '',
    luas VARCHAR(50) DEFAULT '',
    tahun VARCHAR(20) DEFAULT '',
    lokasi TEXT,
    status_tanah VARCHAR(100) DEFAULT '',
    sertifikat VARCHAR(150) DEFAULT '',
    penggunaan VARCHAR(255) DEFAULT '',
    sumber VARCHAR(100) DEFAULT '',
    harga VARCHAR(100) DEFAULT '',
    lampiran VARCHAR(255) DEFAULT '',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS kib_b (
    id INT AUTO_INCREMENT PRIMARY KEY,
    kode VARCHAR(100) NOT NULL UNIQUE,
    jenis VARCHAR(100) DEFAULT '',
    nama VARCHAR(255) NOT NULL,
    no_reg VARCHAR(50) DEFAULT '',
    merk VARCHAR(150) DEFAULT '',
    spesifikasi TEXT,
    bahan VARCHAR(150) DEFAULT '',
    no_pabrik VARCHAR(100) DEFAULT '',
    tahun VARCHAR(20) DEFAULT '',
    jumlah VARCHAR(50) DEFAULT '1 Unit',
    harga VARCHAR(100) DEFAULT '',
    sumber VARCHAR(100) DEFAULT '',
    lampiran VARCHAR(255) DEFAULT '',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

