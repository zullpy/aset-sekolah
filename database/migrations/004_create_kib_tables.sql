CREATE TABLE IF NOT EXISTS kib_activities (
    id INT AUTO_INCREMENT PRIMARY KEY,
    teks VARCHAR(255) NOT NULL,
    pelaku VARCHAR(100) NOT NULL DEFAULT 'Administrator',
    waktu VARCHAR(50) DEFAULT 'Baru saja',
    warna VARCHAR(30) DEFAULT '#852019',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
